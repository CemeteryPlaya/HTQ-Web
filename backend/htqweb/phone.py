"""Сравнение телефонных номеров — общий примитив для всех аппок.

Номер хранится ровно так, как его набрал человек: ``+7 (700) 483-55-81``,
``8 700 4835581``, ``+49 30 901820`` (см. frontend/src/components/ui/
international-phone-input.tsx — маска не приводит номер к канону, она его
только форматирует). Поэтому строковое сравнение двух записей одного и того
же номера почти всегда даёт «не совпало»: различаются код страны, скобки,
дефисы и пробелы.

Живёт в ``htqweb/``, а не в аппке, потому что сравнивать номера нужно с ДВУХ
сторон одной задачи: ``apps.users.interface.find_user_matches`` ищет учётку,
похожую на заводимого сотрудника, а ``apps.hr`` тем же критерием ищет уже
существующую карточку. Разъедься эти два критерия — подсказка начнёт
находить пользователя и не находить дубль сотрудника с тем же номером, то
есть будет предлагать завести человека, который уже заведён. Кросс-импорт
приватного хелпера соседа запрещён (apps/core/tests/test_app_isolation.py),
так что общее место для него — здесь.
"""
from __future__ import annotations

from django.db.models import CharField, F, Func, Value

#: Сколько последних цифр сравнивать. Хвоста в 10 цифр хватает, чтобы
#: различить людей, и он одинаков у ``+7 700…`` и ``8 700…`` — записей
#: одного номера, различающихся лишь формой записи кода страны.
TAIL_DIGITS = 10

#: Короче этого номер не опознаёт человека: по трём-четырём цифрам в
#: совпадение попадут случайные люди, и подсказка станет шумом. Такой
#: запрос честнее не отвечать вовсе.
MIN_DIGITS = 7


def digits(value: str | None) -> str:
    """Только цифры номера, без кода-разделителей и плюса."""
    return "".join(ch for ch in (value or "") if ch.isdigit())


def comparable_tail(value: str | None) -> str:
    """Хвост номера для сравнения; ``""`` — сравнивать нечего (см. MIN_DIGITS)."""
    only_digits = digits(value)
    if len(only_digits) < MIN_DIGITS:
        return ""
    return only_digits[-TAIL_DIGITS:]


def digits_expr(field: str = "phone"):
    """ORM-выражение «номер без разделителей» — считает БАЗА, не Python.

    Применяется как ``.annotate(_digits=digits_expr()).filter(
    _digits__endswith=comparable_tail(номер))``.

    ``regexp_replace`` — postgres-специфичная функция, и это осознанно: у
    платформы один движок, и тесты идут против настоящего Postgres, а не
    SQLite (CLAUDE.md). Альтернатива — поднять в память все строки с
    непустым телефоном и отфильтровать циклом.
    """
    return Func(
        F(field), Value(r"[^0-9]"), Value(""), Value("g"),
        function="regexp_replace", output_field=CharField(),
    )
