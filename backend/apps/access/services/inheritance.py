"""Наследование прав должности вверх по дереву владения компаний — блок C.

Ядро блока: сотрудник вышестоящей компании, чья должность помечена
обслуживающей дочерние компании, несёт роли этой должности во все компании
ниже по дереву владения — не поимённой раздачей, а признаком на должности
(решение заказчика 1). Поимённое назначение (``RoleAssignment``) остаётся
исключением, закрывающим то, что должность закрыть не может (директор без
кадровой карточки, врио, временное расширение) — штатным путём выдачи прав
здесь становится должность, а не рука администратора.

Признак — ``Position.serves_subsidiaries`` — заведён ОТДЕЛЬНО от
``is_manager``/``external_hierarchy`` внешней иерархии (``hierarchy.py``),
и это тоже решение заказчика (2), а не вкус реализации: «начальник людей» и
«работает на всю группу» — разные вещи. В холдинге обслуживают дочерние
компании 8 менеджеров (главбух, кадровый бухгалтер, экономист-аналитик,
ГИП и т.д.), и ни один из них не руководит сотрудниками дочерней компании —
переиспользовать ``is_manager`` значило бы либо соврать во внешней иерархии
блока B, либо не дать прав тем, кто их фактически должен получать.

Обход идёт ВВЕРХ, а не вниз, потому что вопрос, на который отвечает эта
функция, — «кто НАДО МНОЙ даёт мне полномочия здесь», а не «кем я командую
отсюда» (тот вопрос уже отвечен ``hierarchy.subordinate_companies`` и
устроен ровно наоборот — вниз по поддереву). Разрешение прав считается для
ОДНОГО пользователя в ОДНОЙ компании на каждый гейтуемый запрос: подняться
от неё к предкам, каждый из которых самостоятельно решает, работает ли в нём
этот человек, — обход ровно в размер вопроса. Спуск вниз потребовал бы
обратного: перебрать ВСЕ компании платформы в поисках тех, что ниже, — той
работой уже занят ``hierarchy.companies_below``, и здесь она не нужна: кто
предок у данной компании, отвечает один проход по ``parent_slug``.
"""

from __future__ import annotations

from apps.access.models import PositionRole, ScopeKind
from htqweb.fallback import fallback
from htqweb.tenancy.db import use_company


def ancestors_of(company: str) -> list[str]:
    """Слаги компаний строго ВЫШЕ ``company``, от родителя и дальше вверх.

    Архивные предки здесь не отбрасываются — это первый шаг обхода дерева,
    а не решение о том, чьи роли действуют; отбраковку архивных ведёт
    ``inherited_role_scopes`` (решение 7: архив выведен из эксплуатации,
    но выше по дереву может быть действующий предок, и обход не должен
    останавливаться на архивной ступени).

    Защита от цикла — тем же приёмом, что ``hierarchy.companies_below``:
    множество уже пройденных слагов. ``Company.parent`` — self-FK без
    проверки ацикличности (``PROTECT`` её не даёт), и цикл, заведённый в
    обход приложения (прямой ``UPDATE`` в БД), не должен вешать разрешение
    прав — оно выполняется на каждом запросе с гейтом.
    """
    from apps.companies import interface as companies

    result: list[str] = []
    seen = {company}
    row = companies.get_company(company)
    cursor = row.get("parent_slug") if row else None
    while cursor is not None and cursor not in seen:
        seen.add(cursor)
        result.append(cursor)
        row = companies.get_company(cursor)
        cursor = row.get("parent_slug") if row else None
    return result


def inherited_role_scopes(user_id: int, company: str) -> dict[int, tuple[str, int | None]]:
    """Роли, которые ``user_id`` несёт в ``company`` из карточек выше по дереву.

    Для каждого действующего предка ``A``: войти в его схему
    (``htqweb.tenancy.db.use_company``) и спросить кадровую карточку через
    ``hr.get_employee_brief`` — единственный шов с кадровым доменом, как и
    у ``_position_role_ids``/``hierarchy._is_external_manager``. Есть карточка
    и её должность обслуживает дочерние компании → взять роли ЭТОЙ должности,
    как они назначены в ДОМАШНЕЙ для неё компании ``A``
    (``PositionRole.company_slug=A``): роль одна на всю платформу, но набор
    ролей у должности — свой в каждой компании, и должность в холдинге несёт
    именно холдинговый набор.

    Предки НЕ взаимоисключающи (решение 7): обход не прерывается на первой
    найденной карточке, а роли ВСЕХ вышестоящих компаний, где человек
    работает, складываются в один словарь — приоритета между компаниями
    вывести не из чего, и объединение здесь то же самое правило, по которому
    складываются все прочие роли пользователя.

    Архивный предок ролей не даёт (решение 7) — компания выведена из
    эксплуатации, и права её должностей не должны продолжать действовать в
    живых дочерних, — но обход НЕ останавливается на архивной ступени: выше
    может быть действующая.

    Область каждой найденной роли — ``(ScopeKind.COMPANY, None)``: сузить её
    до отдела нельзя, у человека нет отдела в чужой компании.

    Кадровый модуль недоступен на каком-то предке (выключен целиком — глобальный
    рубильник ``ServiceStatus``, единственный, что реально гасит ``hr``: он в
    ``CORE_MODULES``, и компанейский ``CompanyModule`` его не трогает) →
    ``fallback(..., expected=True)`` и этот предок пропускается, ровно как
    ``_position_role_ids`` уже делает для собственной должности — выключенный
    домен не должен молча снимать права.

    ⚠️ ``use_company(A)`` переводит не только ``search_path`` соединения, но и
    контекст компании (``htqweb.tenancy.context``), поэтому
    ``require_service("hr")`` внутри ``get_employee_brief`` спрашивает статус
    именно у ``A`` — предка, чья карточка читается, — а не у компании, из
    которой пришёл запрос. Это и есть желаемое поведение: кадровые данные
    предка управляются рубильником предка.
    """
    from apps.companies import interface as companies
    from apps.hr import interface as hr

    scopes: dict[int, tuple[str, int | None]] = {}
    for ancestor in ancestors_of(company):
        row = companies.get_company(ancestor)
        if row is None or not row.get("is_active"):
            continue

        try:
            with use_company(ancestor):
                brief = hr.get_employee_brief(user_id)
        except Exception as exc:
            fallback("access.inheritance.hr_unavailable", None,
                     reason="кадровый модуль недоступен у предка, наследование "
                            "не посчитано", exc=exc, expected=True,
                     user_id=user_id, company=ancestor)
            continue

        if brief is None or not brief.get("serves_subsidiaries"):
            continue

        role_ids = (
            PositionRole.objects
            .filter(company_slug=ancestor, position_id=brief["position_id"])
            .values_list("role_id", flat=True)
        )
        for role_id in role_ids:
            scopes[role_id] = (ScopeKind.COMPANY, None)
    return scopes
