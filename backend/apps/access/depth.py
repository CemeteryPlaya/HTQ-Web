"""Глубина доступа: четыре признака и пресеты поверх них.

Право описывается не одной ступенью, а НАБОРОМ признаков — так его и
сформулировал заказчик: «может редактировать» у него определено через «может
видеть и вводить», то есть как комбинация, а «может удалять» стоит отдельно.
Строгая лестница этого не выражает: в ней нельзя завести роль, которая чистит
устаревшие записи, но ничего не правит, — а такая роль осмысленна.

Пресеты — те самые шесть названий из постановки. Они не отдельная сущность, а
готовые наборы флагов: в интерфейсе человек выбирает пресет, в хранилище лежат
флаги. Обратно пресет вычисляется (``preset_of``) — если набор совпал с
известным, показываем название, иначе честно показываем сами флаги.

⚠️ ``DELETE`` не включает ``EDIT`` намеренно. «Удалить» и «переписать» — разные
полномочия, и роль «может удалять» из постановки заказчика — это именно право
убрать запись, а не право её менять.
"""

from __future__ import annotations

VIEW = "view"
CREATE = "create"
EDIT = "edit"
DELETE = "delete"

#: Порядок фиксирован: он задаёт порядок колонок в матрице прав и порядок
#: полей в API. Множество для проверок, кортеж — для показа.
FLAGS: tuple[str, ...] = (VIEW, CREATE, EDIT, DELETE)

FLAG_TITLES: dict[str, str] = {
    VIEW: "видит",
    CREATE: "вводит",
    EDIT: "редактирует",
    DELETE: "удаляет",
}

#: Шесть названных уровней из постановки. Ключ уходит в API, значение — набор
#: флагов, который пресет означает.
PRESETS: dict[str, frozenset[str]] = {
    "none": frozenset(),
    "view": frozenset({VIEW}),
    # «Может вводить»: вводить, не видя формы, невозможно физически, поэтому
    # VIEW входит в пресет. Флаги при этом остаются независимыми — набор
    # {CREATE} без VIEW заводится руками, если он кому-то понадобится.
    "create": frozenset({VIEW, CREATE}),
    "edit": frozenset({VIEW, CREATE, EDIT}),
    # «Может удалять» без права переписывать: чистка устаревших записей.
    "delete": frozenset({VIEW, DELETE}),
    "full": frozenset({VIEW, CREATE, EDIT, DELETE}),
}

PRESET_TITLES: dict[str, str] = {
    "none": "нет доступа",
    "view": "видит",
    "create": "может вводить",
    "edit": "может редактировать",
    "delete": "может удалять",
    "full": "полный доступ",
}


def preset_of(flags: frozenset[str] | set[str]) -> str | None:
    """Название пресета для набора флагов, или ``None`` для своей комбинации."""
    wanted = frozenset(flags)
    for name, preset in PRESETS.items():
        if preset == wanted:
            return name
    return None


def flags_of(preset: str) -> frozenset[str]:
    """Набор флагов пресета. Неизвестный пресет — пустой набор, а не ошибка:
    вызывающий получает «нет доступа», то есть самый безопасный исход."""
    return PRESETS.get(preset, frozenset())


# ── Проекция в прежнюю модель ───────────────────────────────────────────────

#: Уровни прежней модели (модуль × none/read/write/admin). Они никуда не
#: делись из ОТВЕТОВ API: на них держатся 47 маршрутов фронта и гейт
#: ``api_view(module=, level=)``. Но источником истины они быть перестали —
#: теперь это проекция глубины, вычисляемая здесь и больше нигде.
LEGACY_NONE = "none"
LEGACY_READ = "read"
LEGACY_WRITE = "write"
LEGACY_ADMIN = "admin"


def legacy_level(flags: frozenset[str] | set[str]) -> str:
    """Набор флагов → уровень прежней модели.

    Соответствие взято из §10 дизайна стадии 2, где оно уже было зафиксировано
    для кадровых уровней: «разрушающие операции ложатся на admin, создание и
    перевод — на write». Здесь то же правило, выраженное во флагах.
    """
    if DELETE in flags:
        return LEGACY_ADMIN
    if CREATE in flags or EDIT in flags:
        return LEGACY_WRITE
    if VIEW in flags:
        return LEGACY_READ
    return LEGACY_NONE
