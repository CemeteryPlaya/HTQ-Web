"""Реестр «какая аппка уже под гейтом модуля» и «какой её ручке гейт не положен».

Часть блока I «Единая модель прав» (задача 3,
``.superpowers/sdd/2026-09-17-block-i-single-rbac/task-3-brief.md``). Гейт
``api_view(module=, level=)`` (``htqweb/http.py``) в этом коммите уже
объявлен, но ни на одну ручку ``access``/``users``/``hr``/``tasks`` ещё не
навешан — задачи 4, 6 и 7 вешают его по одной аппке за коммит (``hr``
разбита на задачи 5 и 6 по экранам, но в реестр попадает только в 6-й —
см. ниже). Этот модуль несёт РОВНО два факта, на которые опирается сторож
``apps/access/tests/test_gate.py::test_gate_covers_every_handle_of_translated_apps``.

1. ``TRANSLATED_APPS`` — какие из четырёх аппок УЖЕ переведены. Пока аппки
   здесь нет, сторож не проверяет её вообще: ни «гейт есть», ни «гейта
   нет» — задача 5 осознанно вешает гейт на часть ручек ``hr`` (справочники
   сотрудников/отделов/должностей/оргструктуры), не трогая эту запись, а
   задача 6 добивает остальные экраны и только тогда включает ``hr`` сюда
   (согласовано в обоих брифах и в предполётной сверке плана,
   ``.superpowers/sdd/2026-09-17-block-i-single-rbac/progress.md``,
   строка «T3 → T4,5,6,7»). Как только аппка появляется здесь, сторож
   требует ``module=`` у КАЖДОЙ её ручки, кроме перечисленных ниже.

2. ``SELF_SERVICE`` — какие ручки переведённой аппки гейта модуля не несут.
   Ручка НЕ самообслуживание — если хоть при каком-то наборе параметров
   отдаёт данные не самого вызывающего. Здесь их две формы:

   - ручка отдаёт СТРОГО данные, привязанные к ``request.token`` (личный
     профиль, свой ``Employee``, свои права), без параметра-подмены, ЛИБО
     общие для компании справочные данные без разбивки по держателю прав
     (производственный календарь, оргдерево) — их не имеет смысла закрывать
     от роли, у которой нет НИ ОДНОГО ``hr.*``-узла (``employee-basic``,
     ``access/migrations/0004_seed_employee_role.py`` — ни одного ``hr.*``
     ключа НЕ содержит; это подтверждено на стенде и является КОРНЕВОЙ
     причиной, почему сплошной гейт ``hr`` без исключений отобрал бы у
     каждого сотрудника его собственную карточку);
   - ручка вообще не проходит JWT (``auth=None`` — ``public/*`` в ``hr``):
     в ``htqweb/http.py::api_view`` проверка ``module=`` стоит ВНУТРИ
     ``if auth is not None:`` — для ``auth=None`` она физически не может
     сработать, поэтому такие ручки сторож пропускает автоматически (см.
     ``test_gate.py::_iter_api_view_calls`` — распознаёт ``auth=None`` в
     теле вызова и не требует для неё ``module=``). Они не перечислены в
     ``SELF_SERVICE`` ниже (нечего анулировать — гейта там и так не может
     быть), но названы в докстринге, потому что бриф просит проверить их
     поимённо: ``hr.public_org_view``, ``hr.public_employee_view``.

   Идентификатор ручки — то же имя, которое сторож достаёт из кода рядом с
   ``api_view(...)``: ``имя_функции`` для вьюх-функций (``hr``/``users``/
   ``tasks`` объявляют каждую ручку отдельной функцией) и ``Класс.метод``
   для class-based вьюх (``access``). Номер строки НЕ годится ключом: любая
   несвязанная правка выше по файлу сдвигает нумерацию и молча ломает
   сверку, а по имени функции запись переживёт такую правку.

⚠️ Ограничение подхода (текстовый разбор, не импорт вьюх — см. докстринг
``test_gate.py``): у ``access`` self-service-ручка обязана иметь
СОБСТВЕННЫЙ, ОТДЕЛЬНЫЙ вызов ``api_view(...)`` — так же, как уже сделано
для ``MyCompaniesView.get`` в ``apps/companies/views.py`` («Без гейта
модуля: это то, что нужно КАЖДОМУ вошедшему, чтобы переключиться») — а не
наследовать декоратор через общий ``read``/``write`` (как сегодня
``MeView.get`` через ``@read``: единственный вызов ``api_view(...)`` на
всю группу read-ручек ``access``). Если задача 4, гейтируя ``access``,
оставит ``MeView.get`` на общем ``@read`` вместо отдельного вызова, сторож
не найдёт совпадения по имени ``MeView.get`` и упадёт отдельной проверкой
(«self_service ссылается на несуществующую ручку») — это СИГНАЛ дать
``/me`` отдельный декоратор, а не ложное срабатывание.
"""

from __future__ import annotations

#: Аппки, чьи ``api_view(...)`` ручки сторож уже требует держать под
#: ``module=``. Пусто до задачи 4 (даст "access", "users"), до задачи 6
#: (добавит "hr" — задача 5 гейтирует часть ручек РАНЬШЕ, чем эта запись
#: появляется, см. докстринг модуля), до задачи 7 (добавит "tasks").
TRANSLATED_APPS: frozenset[str] = frozenset()

#: аппка -> набор ручек-исключений (см. докстринг модуля). Ключи —
#: "access", "users", "hr", "tasks" всегда присутствуют (даже с пустым
#: множеством), чтобы сторож проверял все четыре аппки единообразно.
SELF_SERVICE: dict[str, frozenset[str]] = {
    "access": frozenset({
        # /me — права ТЕКУЩЕГО пользователя, посчитанные по его
        # собственному токену (resolve.resolve_for(request.token, ...)),
        # без параметра, который мог бы указать на чужой user_id. Нужна
        # КАЖДОМУ вошедшему, включая держателя employee-basic, у которой
        # нет ни одного узла access.* — без исключения он не смог бы даже
        # узнать, что ему доступно.
        "MeView.get",
    }),
    "users": frozenset({
        # profile/me GET — _get_profile_user резолвит запись строго по
        # request.token.user_id, параметра-подмены нет.
        "_get_profile",
        # profile/me PATCH — тот же резолвер по user_id; правит только
        # свои поля (display_name/phone/bio/avatar/...).
        "_update_profile",
        # profile/avatar DELETE — свой аватар, тот же _get_profile_user.
        "remove_avatar",
        # смена ПАРОЛЯ — помимо своего user_id требует знания ТЕКУЩЕГО
        # пароля (profile_service.change_password), тем более не может
        # задеть чужую учётку.
        "change_password",
    }),
    "hr": frozenset({
        # employees/me — emp_svc.get_my_employee(request.token); Employee
        # берётся из токена, а не из URL/query.
        "my_employee",
        # employees/me/card — та же привязка к своему Employee; Т2-секции
        # ВНУТРИ карточки уже гейтятся отдельно, полевым RBAC
        # (card_t2_service) — это не входной гейт самой ручки.
        "my_employee_card",
        # employees/me/pmos — тот же get_my_employee под капотом.
        "my_pmos",
        # GET /calendar (год целиком) — общий производственный календарь
        # КОМПАНИИ (рабочие/выходные/праздничные дни), не персональные
        # данные: ответ одинаков для любого вызывающего одной компании.
        # employee-basic не несёт ни одного узла hr.* — без исключения
        # сотрудник не смог бы узнать даже официальные выходные.
        "calendar_year",
        # GET /calendar/working-days — тот же производственный календарь,
        # только диапазоном дат; тот же аргумент, что и у calendar_year.
        "calendar_working_days",
        # GET /org/tree — оргструктура компании; уже сегодня открыта
        # любому авторизованному (в коде нет ни единой проверки прав до
        # этой задачи) — директория из имён/должностей, а не данные,
        # которые нужно скрывать от employee-basic.
        "org_tree",
        # public/org/<token> — auth=None: доступ по опаковому токену
        # ссылки (share_link_service.consume_link); у запроса нет
        # JWT/user_id, гейту module= физически нечего проверять (см.
        # докстринг модуля и htqweb/http.py). Перечислена здесь для
        # ясности «проверено поимённо», реального ограничения не несёт.
        "public_org_view",
        # public/employee/<token> — то же самое, для карточки сотрудника.
        "public_employee_view",
    }),
    # tasks: самообслуживания НЕТ. "Свои" задачи и ежедневка обеспечены
    # ролью employee-basic (tasks.tasks/tasks.daily_reports —
    # access/migrations/0004_seed_employee_role.py), а не исключением из
    # гейта: без этой роли пусто и то, и другое, гейт остаётся общим
    # правилом для всех ручек tasks (см. бриф задачи 7).
    "tasks": frozenset(),
}
