"""Праздничные дни Республики Казахстан — общий источник для всех аппок.

Живёт в ``apps.core``, потому что праздник — не свойство домена: одна и та же
дата обязана одинаково выглядеть и в производственном календаре задач
(``apps.tasks``), и в норме рабочего времени сотрудника (``apps.hr``).
``core`` — единственный разделяемый фундамент (белый список ``_SHARED`` в
``apps/core/tests/test_app_isolation.py``), так что импортировать его напрямую
можно откуда угодно, не нарушая правило «сосед только через interface».

Модель данных здесь двухслойная — ровно по тому, как праздники устроены в
законе:

* ``KZ_FIXED_HOLIDAYS`` — даты, закреплённые за числом месяца. Вычисляются для
  ЛЮБОГО года, поэтому календарь не может «кончиться» — до этого модуля вся
  платформа знала ровно один захардкоженный 2026-й, а 2027-й выходил из бэка
  как голая сетка пн-пт/сб-вс без единого праздника.
* ``KZ_YEAR_OVERRIDES`` — то, что вычислить нельзя: лунный Курбан-айт и разовые
  решения правительства. Дополняется одной строкой на год и является последним
  словом (см. стадию 3 в ``holidays_for_year``).

Правило переноса (ТК РК ст. 84 п. 2: праздник, совпавший с выходным, переносит
день отдыха на следующий рабочий) реализовано движком, а не переписано в
данные. Проверено, что фиксированные даты + это правило + один Курбан-айт
воспроизводят прежний захардкоженный 2026 год дата-в-дату — это зафиксировано
тестом ``test_kz_holidays.py::test_2026_matches_the_hardcoded_table``.
"""

from __future__ import annotations

from datetime import date, timedelta
from functools import lru_cache
from types import MappingProxyType
from typing import Mapping

# (месяц, число) -> название. Источник: Закон РК «О праздниках в Республике
# Казахстан» + ТК РК ст. 84; сверено с календарём gov.kz на 2026 год
# (https://www.gov.kz/article/33969?lang=ru).
KZ_FIXED_HOLIDAYS: dict[tuple[int, int], str] = {
    (1, 1): "Новый год",
    (1, 2): "Новый год",
    (1, 7): "Православное Рождество",
    (3, 8): "Международный женский день",
    (3, 21): "Наурыз мейрамы",
    (3, 22): "Наурыз мейрамы",
    (3, 23): "Наурыз мейрамы",
    (5, 1): "Праздник единства народа Казахстана",
    (5, 7): "День защитника Отечества",
    (5, 9): "День Победы",
    (7, 6): "День Столицы",
    (8, 30): "День Конституции Республики Казахстан",
    (10, 25): "День Республики",
    (12, 16): "День Независимости",
}

# Год -> {дата: название}. Название ``None`` означает «убрать этот день» — так
# снимается и лишний авто-перенос, если правительство его не дало.
#
# Курбан-айт плавает по лунному календарю (~11 дней назад в год) и официально
# объявляется ДУМК/постановлением ближе к году. 2026 (27 мая) и 2027 (16 мая,
# воскресенье) подтверждены; дальше — расчётная оценка, ПРОВЕРИТЬ и поправить
# одной строкой, когда дата станет официальной.
KZ_YEAR_OVERRIDES: dict[int, dict[date, str | None]] = {
    2025: {date(2025, 6, 6): "Курбан-айт"},
    2026: {date(2026, 5, 27): "Курбан-айт"},
    2027: {date(2027, 5, 16): "Курбан-айт"},
    2028: {date(2028, 5, 5): "Курбан-айт"},    # ПРОВЕРИТЬ
    2029: {date(2029, 4, 24): "Курбан-айт"},   # ПРОВЕРИТЬ
    2030: {date(2030, 4, 13): "Курбан-айт"},   # ПРОВЕРИТЬ
}

TRANSFER_SUFFIX = " (перенос)"


def _apply_overrides(days: dict[date, str], year: int) -> None:
    for day, name in KZ_YEAR_OVERRIDES.get(year, {}).items():
        if name is None:
            days.pop(day, None)
        else:
            days[day] = name


def _add_transfers(days: dict[date, str]) -> None:
    """Перенести каждый праздник, попавший на сб/вс, на ближайший свободный
    рабочий день.

    Обход идёт по снимку (``sorted``), а занятость проверяется по живому
    словарю — благодаря этому цели накапливаются: 21 (сб) и 22 (вс) марта
    2026-го дают 24 и 25 марта, а не оба 24-е.
    """
    for day in sorted(days):
        if day.weekday() < 5:
            continue
        target = day + timedelta(days=1)
        while target.weekday() >= 5 or target in days:
            target += timedelta(days=1)
        days[target] = days[day] + TRANSFER_SUFFIX


@lru_cache(maxsize=64)
def holidays_for_year(year: int) -> Mapping[date, str]:
    """Все праздничные дни года: дата -> название.

    Три стадии, порядок важен:

    1. фиксированные даты, спроецированные на ``year``;
    2. словарь года — ДО переносов, чтобы плавающий праздник тоже получил
       перенос (Курбан-айт 2027 падает на воскресенье);
    3. переносы, и затем словарь года ЕЩЁ РАЗ — как последнее слово. Так одна
       строка в ``KZ_YEAR_OVERRIDES`` чинит любое расхождение с постановлением
       правительства, не трогая движок.
    """
    days = {date(year, month, day): name
            for (month, day), name in KZ_FIXED_HOLIDAYS.items()}
    _apply_overrides(days, year)
    _add_transfers(days)
    _apply_overrides(days, year)
    return MappingProxyType(dict(sorted(days.items())))


def holiday_note(day: date) -> str | None:
    """Название праздника или ``None``.

    Год берётся из самой даты, поэтому функция корректна и на отрезке, который
    пересекает 1 января, — вызывающему не нужно знать про устройство таблиц.
    """
    return holidays_for_year(day.year).get(day)


def is_holiday(day: date) -> bool:
    return day in holidays_for_year(day.year)
