/**
 * Локальная дата — там, где `toISOString()` тихо подставляет вчера.
 *
 * `new Date().toISOString().slice(0, 10)` берёт дату по UTC: до 05:00 по
 * Алматы (`UTC+5`) она на сутки меньше текущей местной. Симптом обычно
 * незаметен разработчику (часовой пояс машины редко совпадает с рабочим),
 * но человек в Алматы получает «сегодня» вчерашним числом — в форме по
 * умолчанию или в бейдже «истекло», загорающемся на день раньше срока.
 *
 * Формат — `ГГГГ-ММ-ДД`, тот же, что ждут `<DateInput>` и бэкенд.
 */
export function todayIso(): string {
  const now = new Date();
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}
