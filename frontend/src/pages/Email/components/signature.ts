/**
 * Подстановка подписи в тело письма.
 *
 * Подпись вставляется В РЕДАКТОР, а не приклеивается на сервере при отправке:
 * человек должен видеть, что именно уйдёт от его имени, и иметь возможность
 * это поправить. Невидимая добавка к письму — худший вид сюрприза.
 *
 * Отдельный модуль, а не часть ComposeDialog: это чистые функции над строкой,
 * и держать их рядом с компонентом значит и ломать hot-reload, и мешать
 * тестировать логику без монтирования диалога.
 */

/**
 * Общепринятый разделитель подписи (RFC 3676 §4.3) — его понимают почтовые
 * клиенты и умеют сворачивать при цитировании.
 */
export const SIGNATURE_SEPARATOR = '\n\n-- \n';

/**
 * Дописать подпись к телу письма.
 *
 * Возвращает исходный текст, если подписи нет или она уже на месте: смена
 * отправителя туда-обратно не должна плодить копии.
 */
export const withSignature = (body: string, signature?: string | null): string => {
    const trimmed = (signature || '').trim();
    if (!trimmed) return body;
    if (body.includes(trimmed)) return body;
    return `${body}${SIGNATURE_SEPARATOR}${trimmed}`;
};

/**
 * Заменить подпись прежнего отправителя на подпись нового.
 *
 * Именно заменить, а не дописать: сменив адрес в селекторе, человек ожидает
 * увидеть одну подпись, а не две — свою старую и свою новую.
 */
export const replaceSignature = (
    body: string, previous?: string | null, next?: string | null,
): string => {
    const old = (previous || '').trim();
    let base = body;
    if (old) {
        base = base.replace(`${SIGNATURE_SEPARATOR}${old}`, '');
        // Подпись могла попасть в тело и без разделителя — например, её
        // вставили до того, как отправителя сменили в первый раз.
        if (base === body) base = base.replace(old, '').trimEnd();
    }
    return withSignature(base, next);
};
