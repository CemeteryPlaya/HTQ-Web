/**
 * Почему у строки contracts нельзя нажать «На согласование».
 *
 * У согласуемой строки две независимые оси: `approval_state` ведёт signoff,
 * `status` — своя машина статусов домена. Кнопку рисует `approval_state`, а
 * `/submit` предметной аппки смотрит на `status` — потому что уже
 * согласованную строку отправлять некуда, а «на согласовании» её ставит сам
 * движок.
 *
 * Оси расходятся штатным путём: договор заводят сразу в статусе «Подписан»
 * (задним числом), у счёта статус двигают руками из карточки. Без этой
 * проверки кнопка предлагала действие, которое гарантированно отвечало 409,
 * — и текст 409 был единственным способом узнать причину.
 *
 * Формулировки совпадают с серверными ДОСЛОВНО, и это обязательство, а не
 * совпадение: пользователь, который всё-таки увидит 409 (гонка, старая
 * вкладка), должен прочитать то же самое, а не два разных объяснения одного
 * запрета. Меняете текст в `*_service.py` — меняйте здесь.
 *
 * Правил здесь три, потому что на сервере их три разных:
 *
 *   • `draftOnlySubmitBlock` — шесть сущностей, у которых `/submit` требует
 *     черновика (договор, счёт, заявка, предоплата, акт, оплата);
 *   • `budgetSubmitBlock` — у бюджета своё: закрытый и пустой;
 *   • `counterpartySubmitBlock` — у контрагента своё: заблокированный.
 *
 * Авансовый отчёт сюда НЕ попал намеренно: его `/submit` запирают владелец
 * заявки, её открытость и остаток невыбранной суммы — это не про статус
 * самой строки, и заочно на фронте не вычисляется.
 */

/**
 * Как называется предмет в тексте отказа. Именительный падеж: подставляется
 * в «…; <предмет> в статусе «Черновик»».
 */
export type DraftOnlySubject =
  | 'договор'
  | 'счёт'
  | 'заявка'
  | 'предоплата'
  | 'акт'
  | 'оплата';

/**
 * Отправка заперта, пока строка не черновик.
 *
 * Зеркалит `submit_for_approval` шести сервисов contracts. `null` — путь
 * свободен (по этой оси; остальные проверки остаются за сервером).
 */
export function draftOnlySubmitBlock(
  status: string,
  statusLabel: string,
  subject: DraftOnlySubject,
): string | null {
  if (status === 'draft') return null;
  return `На согласование отправляется черновик; ${subject} в статусе «${statusLabel}»`;
}

/**
 * Отправка бюджета: `budget_service.submit_for_approval`.
 *
 * Два запрета вместо одного: закрытый бюджет согласовывать нечего (его
 * жизненный цикл завершён), пустой — тоже, согласующему нечего утверждать.
 *
 * `lineCount` — `null`/`undefined`, когда состав строк в этом месте неизвестен
 * (реестр может отдавать бюджет без `lines`). Тогда про пустоту МОЛЧИМ и
 * пропускаем к серверу: ложная блокировка хуже 409, потому что 409 объяснит
 * причину, а погашенная кнопка — нет.
 */
export function budgetSubmitBlock(
  status: string,
  lineCount: number | null | undefined,
): string | null {
  if (status !== 'active') return 'Закрытый бюджет на согласование не отправляется';
  if (lineCount === 0) return 'В бюджете нет ни одной программы — согласовывать нечего';
  return null;
}

/**
 * Отправка контрагента: `counterparty_service.submit_for_approval`.
 *
 * Запрет один: по заблокированному решение уже принято, и оно отрицательное.
 * `inactive` при этом отправлять МОЖНО — сервер его не запрещает, и
 * повторять здесь чужую строгость нельзя.
 */
export function counterpartySubmitBlock(status: string): string | null {
  if (status === 'blocked') {
    return 'Заблокированный контрагент на согласование не отправляется';
  }
  return null;
}
