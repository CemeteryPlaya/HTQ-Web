/**
 * База остаточного долга по размерам тач-целей.
 *
 * Почему она вообще есть: правила «переполнение» и «автозум» доведены до нуля
 * и проверяются строго. А тач-цели — это десятки мест (иконки в плотных
 * таблицах, инлайновые ссылки в карточках, кастомные тулбары), и разом их не
 * переделать, не переверстав половину рабочих экранов. Чтобы тест был полезен
 * уже сегодня, он работает как храповик: экран не может стать хуже своей
 * записи здесь.
 *
 * Считаются НЕ срабатывания, а уникальные компоненты-виновники: на списке из
 * 30 строк одно место вёрстки даёт 30 нарушений, и порог зависел бы от объёма
 * данных в базе. Поэтому, например, у `/tasks` здесь 8, а не 145.
 *
 * Правила работы с файлом:
 *   • число можно только УМЕНЬШАТЬ;
 *   • новый экран добавляется со значением 0;
 *   • если экрана нет в таблице, порог по умолчанию 0.
 *
 * Актуальные числа печатает `npm run test:mobile:probe` строками `BASELINE`.
 */
export const touchTargetBaseline: Record<string, number> = {
  // ── Публичная часть ───────────────────────────────────────────────────
  // Главная: индикаторы каруселей и мелкие ссылки в футере.
  '/': 4,
  '/services': 1,
  '/contacts': 1,
  '/login': 2,

  // ── Рабочие разделы ───────────────────────────────────────────────────
  '/myprofile': 1,
  '/messenger': 2,
  '/email': 3,
  // Карточки задач — плотная сводка: внутри каждой лежат вторичные
  // affordance'ы (ссылка на проект, код задачи, приоритет, прогресс), а
  // основная цель нажатия — сама карточка. Осознанный долг, не поломка.
  '/tasks': 8,
  '/requests': 1,
  '/requests/my-stats': 1,
  '/contracts': 1,
  '/contracts/budgets': 1,
  '/contracts/counterparties': 1,
  '/contracts/agreements': 1,
  '/signoff': 1,
  '/signoff/processes': 1,
  '/hr/employees': 1,
  '/hr/departments': 2,
  '/hr/positions': 2,
  // Кнопки зума/центровки холста react-flow — часть библиотеки.
  '/hr/org-chart': 4,
  '/admin/users': 1,
};

/** Порог для экрана; для отсутствующих в таблице — ноль. */
export function baselineFor(path: string): number {
  return touchTargetBaseline[path] ?? 0;
}
